"""Check live counters, refresh/reset behavior, and streaming packet decoding.

Run: python3 type2_live_checks.py. Synthetic packets are written to files only;
no router or robot traffic is generated by these checks.
"""

import json
import tempfile
import time
import unittest
from pathlib import Path

from flask import Flask
from scapy.all import wrpcap

import evpn_capture as capture
from capture_decoder_checks import _packet, _type2, _update
from evpn_type2_live import Type2LiveMonitor
from type2_live_server import Type2ChartState, register_type2_chart


def _event(run_id="run-a", started=100, status="running"):
    """Build one two-spine snapshot for counter/API tests."""
    return {
        "run_id": run_id, "started_epoch": started, "status": status,
        "by_capture_point": {
            "spine1": {"advertisement": 3, "withdrawal": 1},
            "spine2": {"advertisement": 4, "withdrawal": 2},
        },
    }


class LiveChecks(unittest.TestCase):
    """Exercise state handling and a real TShark stream without a topology."""

    def test_combined_counts_and_refresh(self):
        """The total equals both points and remains available to a new page."""
        app = Flask(__name__, template_folder=str(Path(__file__).parent / "templates"))
        register_type2_chart(app)
        client = app.test_client()
        self.assertEqual(client.get("/type2-chart").status_code, 200)
        self.assertEqual(client.get("/api/type2-counts").json["status"], "waiting")
        self.assertEqual(client.post("/type2-event", json=_event()).status_code, 200)
        first = client.get("/api/type2-counts").json
        second = client.get("/api/type2-counts").json
        self.assertEqual(first["current"]["total"], {"advertisement": 7, "withdrawal": 3})
        self.assertEqual(first, second)
        self.assertEqual(first["current"]["by_capture_point"]["spine2"]["advertisement"], 4)

    def test_new_run_resets_and_old_run_is_ignored(self):
        """A new capture starts a fresh series; delayed old updates cannot reset it."""
        state = Type2ChartState()
        state.accept(_event())
        fresh = _event("run-b", 200)
        fresh["by_capture_point"]["spine1"]["advertisement"] = 0
        state.accept(fresh)
        self.assertEqual(len(state.snapshot()["history"]), 1)
        self.assertFalse(state.accept(_event()))
        self.assertEqual(state.snapshot()["run_id"], "run-b")

    def test_invalid_or_decreasing_counts_are_rejected(self):
        """Reject malformed data instead of silently corrupting chart totals."""
        state = Type2ChartState()
        state.accept(_event())
        decreasing = _event()
        decreasing["by_capture_point"]["spine1"]["advertisement"] = 1
        with self.assertRaises(ValueError):
            state.accept(decreasing)
        invalid = _event()
        invalid["by_capture_point"]["spine1"]["withdrawal"] = -1
        with self.assertRaises(ValueError):
            state.accept(invalid)
        self.assertEqual(state.snapshot()["current"]["total"]["advertisement"], 7)

    def test_history_is_bounded_and_stopped_status_is_retained(self):
        """Long pauses do not grow history forever or leave a false live status."""
        state = Type2ChartState()
        for unused_index in range(305):
            state.accept(_event())
        state.accept(_event(status="stopped"))
        self.assertEqual(len(state.snapshot()["history"]), 300)
        self.assertEqual(state.snapshot()["status"], "stopped")

    def test_routes_are_counted_before_stream_stops(self):
        """A still-open growing capture updates counts before EOF or capture stop."""
        with tempfile.TemporaryDirectory(prefix="type2_live_check_") as directory:
            pcap_path = Path(directory) / "spine1.pcapng"
            payload = _update(_type2("11") + _type2("12", False), _type2("21"), sequence=1)
            wrpcap(str(pcap_path), [_packet(payload)])
            session = {
                "directory": directory, "started_epoch": time.time(),
                "captures": [{"capture_point": "spine1", "pcap_path": str(pcap_path)}],
            }
            monitor = Type2LiveMonitor(session, capture._pdml_type2_rows, "http://127.0.0.1:1")
            try:
                monitor.start()
                deadline = time.monotonic() + 5
                while time.monotonic() < deadline:
                    counts = monitor.snapshot("running")["by_capture_point"]["spine1"]
                    if counts["advertisement"] == 2 and counts["withdrawal"] == 1:
                        break
                    time.sleep(0.05)
                self.assertEqual(counts, {"advertisement": 2, "withdrawal": 1})
                self.assertFalse(monitor.stop_event.is_set())
                # Append another packet while the same stream is still open.
                second = _packet(_update(_type2("22"), sequence=2), sequence=1 + len(payload))
                wrpcap(str(pcap_path), [second], append=True)
                deadline = time.monotonic() + 5
                while time.monotonic() < deadline:
                    counts = monitor.snapshot("running")["by_capture_point"]["spine1"]
                    if counts["advertisement"] == 3:
                        break
                    time.sleep(0.05)
                self.assertEqual(counts["advertisement"], 3)
            finally:
                path = monitor.stop()
            final = json.loads(Path(path).read_text())
            self.assertEqual(final["status"], "stopped")
            self.assertEqual(final["errors"], [])


if __name__ == "__main__":
    unittest.main(verbosity=2)
